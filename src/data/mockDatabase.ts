const STORAGE_KEYS = {
  RULES: 'procode_rules_v2',
  FACTS: 'procode_facts_v2',
  DICTIONARY: 'procode_dict_v2',
  SUBMISSIONS: 'procode_submissions_v2',
  METRICS: 'procode_metrics_v2',
  CURRENT_USER: 'procode_current_user_v2',
};

export const getStoredData = () => {
  try {
    const rules = localStorage.getItem(STORAGE_KEYS.RULES);
    const facts = localStorage.getItem(STORAGE_KEYS.FACTS);
    const dict = localStorage.getItem(STORAGE_KEYS.DICTIONARY);
    const submissions = localStorage.getItem(STORAGE_KEYS.SUBMISSIONS);
    const metrics = localStorage.getItem(STORAGE_KEYS.METRICS);

    return {
      rules: rules ? JSON.parse(rules) : INITIAL_RULES,
      facts: facts ? JSON.parse(facts) : INITIAL_FACTS,
      dictionary: dict ? JSON.parse(dict) : INITIAL_DICTIONARY,
      submissions: submissions ? JSON.parse(submissions) : INITIAL_SUBMISSIONS,
      metrics: metrics ? JSON.parse(metrics) : INITIAL_METRICS,
    };
  } catch {
    return {
      rules: INITIAL_RULES,
      facts: INITIAL_FACTS,
      dictionary: INITIAL_DICTIONARY,
      submissions: INITIAL_SUBMISSIONS,
      metrics: INITIAL_METRICS,
    };
  }
};

export const saveStoredData = (data: {
  rules?: BrandRule[];
  facts?: LivingFact[];
  dictionary?: DictionaryTerm[];
  submissions?: ContentSubmission[];
  metrics?: GovernanceMetrics;
}) => {
  try {
    if (data.rules) localStorage.setItem(STORAGE_KEYS.RULES, JSON.stringify(data.rules));
    if (data.facts) localStorage.setItem(STORAGE_KEYS.FACTS, JSON.stringify(data.facts));
    if (data.dictionary) localStorage.setItem(STORAGE_KEYS.DICTIONARY, JSON.stringify(data.dictionary));
    if (data.submissions) localStorage.setItem(STORAGE_KEYS.SUBMISSIONS, JSON.stringify(data.submissions));
    if (data.metrics) localStorage.setItem(STORAGE_KEYS.METRICS, JSON.stringify(data.metrics));
  } catch (e) {
    console.error('Failed to save to mock PostgreSQL local storage', e);
  }
};
